def test_pricing_invariant_under_valuation_date_shift(client: TestClient):
    """Holding ``t`` constant, greeks must not depend on ``valuation_date``.

    The pricer is keyed on time-to-expiry ``t`` (ACT/365 years), not on the
    absolute calendar date.  This test documents and enforces that property,
    which previously appeared as 12 redundant ``_holiday`` golden entries
    (same ``t``, only ``valuation_date`` differed, identical greeks).
    """
    base_params = {
        "s": 100, "k": 100, "t": 0.25, "r": 0.05, "q": 0.02,
        "v": 0.20, "type": "call", "style": "european",
    }
    resp_mon = client.get(
        "/v1/greeks",
        params={**base_params, "valuation_date": "2026-04-20"},
        headers={"Accept": "application/json"},
    )
    resp_holiday = client.get(
        "/v1/greeks",
        params={**base_params, "valuation_date": "2026-04-28"},
        headers={"Accept": "application/json"},
    )
    assert resp_mon.status_code == 200
    assert resp_holiday.status_code == 200
    out_mon = resp_mon.json()["greeks"]["outputs"]
    out_hol = resp_holiday.json()["greeks"]["outputs"]
    for greek, val in out_mon.items():
        assert val == pytest.approx(out_hol[greek], abs=1e-10), (
            f"{greek}: {val} != {out_hol[greek]} under valuation_date shift"
        )
